/**
 * Busca por termo ou CBO no catálogo
 */
export function buscarCboNoCatalogo(termo: string): CboItem[] {
  if (!termo || !termo.trim()) return CATALOGO_CBO;
  const t = termo.toLowerCase().trim();
  const tClean = t.replace(/[^0-9]/g, "");

  return CATALOGO_CBO.filter((item) => {
    const matchCbo = item.cbo.toLowerCase().includes(t) || (tClean.length >= 2 && item.cbo.replace(/[^0-9]/g, "").includes(tClean));
    const matchTitulo = item.titulo.toLowerCase().includes(t);
    const matchSinonimos = item.sinonimos.some((s) => s.toLowerCase().includes(t));
    const matchGrupo = item.grupoOcupacional.toLowerCase().includes(t);
    const matchDesc = item.descricaoSumaria.toLowerCase().includes(t);

    return matchCbo || matchTitulo || matchSinonimos || matchGrupo || matchDesc;
  });
}
